/* ====================================================================== */
/* Text mode                                                               */
/* ====================================================================== */

static inline uint16_t* vga_text_base(void)
{
    return (uint16_t*)PHYS_TO_VIRT(VGA_TEXT_MEM);
}

static inline uint16_t vga_entry(char c, uint8_t color)
{
    return (uint16_t)((uint8_t)c | ((uint16_t)color << 8));
}

void vga_init(void)
{
    vga_row = 0;
    vga_col = 0;
    vga_color = VGA_ENTRY_COLOR(VGA_COLOR_LIGHT_GREY, VGA_COLOR_BLACK);
    vga_clear(vga_color);
    vga_enable_cursor(14, 15);
    vga_set_cursor(0, 0);
}

void vga_clear(uint8_t color)
{
    uint16_t* buf = vga_text_base();
    uint16_t  entry = vga_entry(' ', color);
    uint32_t  i;
    for (i = 0; i < VGA_TEXT_WIDTH * VGA_TEXT_HEIGHT; i++) {
        buf[i] = entry;
    }
    vga_row = 0;
    vga_col = 0;
}

void vga_scroll(void)
{
    uint16_t* buf = vga_text_base();
    uint32_t  i;

    /* Move lines 1..24 up to lines 0..23. */
    for (i = 0; i < (uint32_t)(VGA_TEXT_HEIGHT - 1) * VGA_TEXT_WIDTH; i++) {
        buf[i] = buf[i + VGA_TEXT_WIDTH];
    }
    /* Blank the last line. */
    for (i = (VGA_TEXT_HEIGHT - 1) * VGA_TEXT_WIDTH;
         i < (uint32_t)VGA_TEXT_HEIGHT * VGA_TEXT_WIDTH; i++) {
        buf[i] = vga_entry(' ', vga_color);
    }
    vga_row = VGA_TEXT_HEIGHT - 1;
}

void vga_putc(char c, uint8_t color)
{
    uint16_t* buf = vga_text_base();

    switch (c) {
    case '\n':                      /* newline */
        vga_row++;
        vga_col = 0;
        break;
    case '\r':                      /* carriage return */
        vga_col = 0;
        break;
    case '\b':                      /* backspace */
        if (vga_col > 0) {
            vga_col--;
        } else if (vga_row > 0) {
            vga_row--;
            vga_col = VGA_TEXT_WIDTH - 1;
        }
        buf[vga_row * VGA_TEXT_WIDTH + vga_col] = vga_entry(' ', color);
        break;
    case '\t':                      /* tab: advance to next 8-column stop */
        vga_col = (vga_col + 8) & ~7;
        if (vga_col >= VGA_TEXT_WIDTH) {
            vga_col = 0;
            vga_row++;
        }
        break;
    default:
        buf[vga_row * VGA_TEXT_WIDTH + vga_col] = vga_entry(c, color);
        vga_col++;
        break;
    }

    if (vga_col >= VGA_TEXT_WIDTH) {
        vga_col = 0;
        vga_row++;
    }
    if (vga_row >= VGA_TEXT_HEIGHT) {
        vga_scroll();
    }
    vga_set_cursor((uint8_t)vga_col, (uint8_t)vga_row);
}

void vga_puts(const char* s)
{
    if (s == NULL) {
        return;
    }
    while (*s != '\0') {
        vga_putc(*s++, vga_color);
    }
}

void vga_set_cursor(uint8_t x, uint8_t y)
{
    uint16_t pos = (uint16_t)(y * VGA_TEXT_WIDTH + x);
    outb(0x3D4, 0x0F);              /* cursor location low byte */
    outb(0x3D5, (uint8_t)(pos & 0xFF));
    outb(0x3D4, 0x0E);              /* cursor location high byte */
    outb(0x3D5, (uint8_t)((pos >> 8) & 0xFF));
}

void vga_enable_cursor(uint8_t start, uint8_t end)
{
    outb(0x3D4, 0x0A);              /* cursor start register */
    outb(0x3D5, (uint8_t)(start & 0x1F));   /* bit5=0 -> enabled */
    outb(0x3D4, 0x0B);              /* cursor end register */
    outb(0x3D5, (uint8_t)(end & 0x1F));
}

void vga_disable_cursor(void)
{
    outb(0x3D4, 0x0A);
    outb(0x3D5, 0x20);              /* bit5=1 -> cursor disabled */
}

