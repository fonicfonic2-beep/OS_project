void vga_gfx_init(multiboot_tag_framebuffer_t* fb)
{
    uintptr_t phys;

    /* Prefer the multiboot framebuffer tag; fall back to paging.c globals. */
    if (fb != NULL) {
        g_framebuffer.phys_addr = (uintptr_t)fb->framebuffer_addr;
        g_framebuffer.pitch     = fb->framebuffer_pitch;
        g_framebuffer.width     = fb->framebuffer_width;
        g_framebuffer.height    = fb->framebuffer_height;
        g_framebuffer.bpp       = fb->framebuffer_bpp;
        g_framebuffer.type      = fb->framebuffer_type;
        g_framebuffer.red_pos   = (uint8_t)fb->red_pos;
        g_framebuffer.red_mask  = (uint8_t)fb->red_mask;
        g_framebuffer.green_pos = (uint8_t)fb->green_pos;
        g_framebuffer.green_mask= (uint8_t)fb->green_mask;
        g_framebuffer.blue_pos  = (uint8_t)fb->blue_pos;
        g_framebuffer.blue_mask = (uint8_t)fb->blue_mask;
    } else {
        g_framebuffer.phys_addr = (uintptr_t)g_framebuffer_phys;
        g_framebuffer.pitch     = (uint32_t)g_framebuffer_pitch;
        g_framebuffer.width     = (uint32_t)g_framebuffer_width;
        g_framebuffer.height    = (uint32_t)g_framebuffer_height;
        g_framebuffer.bpp       = (uint8_t)g_framebuffer_bpp;
        g_framebuffer.type      = 1;  /* RGB */
    }

    phys = g_framebuffer.phys_addr;
    g_framebuffer.addr = PHYS_TO_VIRT(phys);

    if (g_framebuffer.pitch == 0) {
        g_framebuffer.pitch = g_framebuffer.width * (g_framebuffer.bpp / 8);
    }
}

static inline uint8_t* gfx_ptr(int x, int y)
{
    uint8_t bytes_per_pixel = (uint8_t)(g_framebuffer.bpp / 8);
    if (bytes_per_pixel == 0) {
        bytes_per_pixel = 4;
    }
    return (uint8_t*)g_framebuffer.addr
           + (uintptr_t)y * g_framebuffer.pitch
           + (uintptr_t)x * bytes_per_pixel;
}

void vga_gfx_putpixel(int x, int y, uint32_t color)
{
    uint8_t* p;
    if (x < 0 || y < 0 ||
        (uint32_t)x >= g_framebuffer.width ||
        (uint32_t)y >= g_framebuffer.height) {
        return;
    }
    p = gfx_ptr(x, y);
    if (g_framebuffer.bpp == 32 || g_framebuffer.bpp == 0) {
        *(uint32_t*)p = color;
    } else if (g_framebuffer.bpp == 24) {
        p[0] = (uint8_t)(color & 0xFF);
        p[1] = (uint8_t)((color >> 8) & 0xFF);
        p[2] = (uint8_t)((color >> 16) & 0xFF);
    } else {
        *(uint32_t*)p = color;
    }
}

uint32_t vga_gfx_getpixel(int x, int y)
{
    uint8_t* p;
    if (x < 0 || y < 0 ||
        (uint32_t)x >= g_framebuffer.width ||
        (uint32_t)y >= g_framebuffer.height) {
        return 0;
    }
    p = gfx_ptr(x, y);
    if (g_framebuffer.bpp == 24) {
        return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16);
    }
    return *(uint32_t*)p;
}

void vga_gfx_fillrect(int x, int y, int w, int h, uint32_t color)
{
    int cx, cy;
    int x0 = x, y0 = y;
    int x1 = x + w, y1 = y + h;

    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if ((uint32_t)x1 > g_framebuffer.width)  x1 = (int)g_framebuffer.width;
    if ((uint32_t)y1 > g_framebuffer.height) y1 = (int)g_framebuffer.height;

    for (cy = y0; cy < y1; cy++) {
        for (cx = x0; cx < x1; cx++) {
            vga_gfx_putpixel(cx, cy, color);
        }
    }
}

void vga_gfx_clearscreen(uint32_t color)
{
    vga_gfx_fillrect(0, 0, (int)g_framebuffer.width, (int)g_framebuffer.height, color);
}

void vga_gfx_drawchar(int x, int y, char c, uint32_t fg, uint32_t bg)
{
    uint8_t idx = (uint8_t)c;
    int row, col;
    for (row = 0; row < 16; row++) {
        uint8_t bits = font8x16[idx][row];
        for (col = 0; col < 8; col++) {
            uint32_t pixel = (bits & (0x80 >> col)) ? fg : bg;
            vga_gfx_putpixel(x + col, y + row, pixel);
        }
    }
}

void vga_gfx_drawstring(int x, int y, const char* s, uint32_t fg, uint32_t bg)
{
    int cx = x;
    if (s == NULL) {
        return;
    }
    while (*s != '\0') {
        if (*s == '\n') {
            y += 16;
            cx = x;
        } else {
            vga_gfx_drawchar(cx, y, *s, fg, bg);
            cx += 8;
        }
        s++;
    }
}

void vga_gfx_line(int x0, int y0, int x1, int y1, uint32_t color)
{
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;
    int x = x0, y = y0;

    for (;;) {
        vga_gfx_putpixel(x, y, color);
        if (x == x1 && y == y1) {
            break;
        }
        {
            int e2 = 2 * err;
            if (e2 > -dy) { err -= dy; x += sx; }
            if (e2 <  dx) { err += dx; y += sy; }
        }
    }
}
